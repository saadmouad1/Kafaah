export const DICT = { ar, en };

export function translate(lang, key, vars) {
  const l = lang === 'en' ? 'en' : 'ar';
  let s = DICT[l][key];
  if (s == null) s = DICT.ar[key] != null ? DICT.ar[key] : key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      s = s.split('{' + k + '}').join(String(vars[k]));
    }
  }
  return s;
}
